const excludedFromQuizScope = new Set([
  "3-1-018", // local-government promotion
  "3-8-021", // education
  "3-8-022", // special education
  "3-8-025", // instructor
]);

export const officialAcademicRoles: OfficialAcademicRole[] = catalogGroups.flatMap(({ id }) =>
  sourceLists[id].split("\n").map((entry) => {
    const [code, title] = entry.split("|");
    return { code, title, groupId: id, inQuizScope: !excludedFromQuizScope.has(code) };
  }),
);

export const scopedAcademicRoles = officialAcademicRoles.filter((role) => role.inQuizScope);
